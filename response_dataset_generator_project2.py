def generate_samples(xx, nSample, nSampleR_obj, NUM_OBJECTIVES, NUM_CONSTRAINTS, constraint_basis_info):
    """
    Generate high-fidelity samples by running all simulation cases (co-simulation and stiffness analyses).
    The objective and constraint functions are assumed to use the same number of samples.
    """
    if not COSIM_AVAILABLE:
        raise ImportError(
            "generate_samples requires the co-simulation automation module 'automotive_script_cosim_v4', "
            "which is not included in this repository."
        )
    
    # Update the input file: save xx to CSV
    # Header matching the number of columns of xx (X_1, X_2, ..., X_n)
    num_cols = xx.shape[1]
    headers = [f"X_{i+1}" for i in range(num_cols)]
    
    input_csv_path = globalVars.filepath + "/data/input_samples.csv"
    df_input = pd.DataFrame(xx, columns=headers)
    df_input.to_csv(input_csv_path, index=False)
    print(f"Input samples saved to: {input_csv_path}")
    
    # Maximum number of samples over the constraint functions
    max_constraint_samples = max(constraint_basis_info[j]['nSampleR'] for j in range(NUM_CONSTRAINTS))
    
    # Number of samples to run
    max_samples = max(nSampleR_obj, max_constraint_samples)
    
    # ========== Run all analyses ==========
    print("Starting full simulations...")
    
    # sim_auto_full = SimpackAutomation(
    #     path_model_car="D:/simpack_adb_2025/ADB_RIGID/0_CAR_RIGID.par.spck",
    #     path_macro_script="D:/simpack_adb_2025/script/car_set_subvars.sjs",
    #     path_input_csv= globalVars.filepath + "/data/input_samples.csv",
    #     path_output_csv= globalVars.filepath + "/data/car_output_samples.csv",
    #     macro_script_generator=generate_car_param_script,
    #     sim_cases=[ride, step, dlc, sscv],  # all cases
    # )

    cosim_auto = CosimAutomation(
        #path_model_car="D:/simpack_adb_2025/ADB_RIGID/0_CAR_RIGID.par.spck",
        #path_macro_script="D:/simpack_adb_2025/script/car_set_subvars.sjs",
        path_input_csv= globalVars.filepath + "/data/input_samples.csv",
        path_output_csv= globalVars.filepath + "/data/car_output_samples.csv",
        sim_cases= [pothole, stiffness], #[pothole],  # Casecontrol
        #path_inp_dir="D:/temp", # folder for the inp files generated by Abaqus
        path_cosim_dir="D:/CO_SIM_TUTORIAL_2025_v3", # co-simulation model folder (user-specific)
        path_work_dir = "D:/CO_SIM_TUTORIAL_2025_v3/CO_SIM_START_2025/script_cosim/work_script",
        path_skip_csv = globalVars.filepath + "/data/car_output_samples_skipped_samples.csv",  # path for the list of skipped samples (optional)
        #macro_script_generator=generate_car_param_script,
        
    )
    
    # Remove an existing output file
    output_csv_path = cosim_auto.path_output_csv
    if os.path.exists(output_csv_path):
        os.remove(output_csv_path)
        print(f"Removed existing output file: {output_csv_path}")

    # Remove an existing skipped-sample file
    skip_csv_path = cosim_auto.path_skip_csv
    if os.path.exists(skip_csv_path):
        os.remove(skip_csv_path)
        print(f"Removed existing skipped samples file: {skip_csv_path}")
    
    # Run the simulations and update skipped_sample_indices
    globalVars.skipped_sample_indices = cosim_auto.run_all(1, max_samples)
    print(f"Simulations completed. Skipped samples (1-based): {globalVars.skipped_sample_indices}")
    
    # Number of rows actually required, accounting for skipped samples
    if globalVars.skipped_sample_indices:
        skipped_indices_0based = set(idx - 1 for idx in globalVars.skipped_sample_indices)
        
        # Rows required for the objective function
        valid_indices_obj = []
        idx = 0
        while len(valid_indices_obj) < nSampleR_obj:
            if idx not in skipped_indices_0based:
                valid_indices_obj.append(idx)
            idx += 1
        n_extended_obj = idx
        
        # Rows required for the constraint functions
        valid_indices_con = []
        idx = 0
        while len(valid_indices_con) < max_constraint_samples:
            if idx not in skipped_indices_0based:
                valid_indices_con.append(idx)
            idx += 1
        n_extended_con = idx
        
        # Maximum number of rows required
        max_rows = max(n_extended_obj, n_extended_con)
        print(f"Adjusted max_rows: {max_rows} (original: {max_samples}, skipped: {len(skipped_indices_0based)})")
    else:
        max_rows = max_samples
        skipped_indices_0based = set()
    
    # Initialize the result array (required size, including NaN rows)
    result = np.full((max_rows, NUM_OBJECTIVES + NUM_CONSTRAINTS), np.nan)
    
    # Process the results
    if os.path.exists(output_csv_path):
        print(f"Loading simulation data from: {output_csv_path}")
        output_df = pd.read_csv(output_csv_path)
        output_data = output_df.values
        
        # Copy output_data into result, split into objective and constraint columns (including NaN rows)
        # Objective data
        result[:output_data.shape[0], :NUM_OBJECTIVES] = output_data[:, :NUM_OBJECTIVES]
        # Constraint data
        result[:output_data.shape[0], NUM_OBJECTIVES:NUM_OBJECTIVES+NUM_CONSTRAINTS] = output_data[:, NUM_OBJECTIVES:NUM_OBJECTIVES+NUM_CONSTRAINTS]
        
        print(f"Data loading completed: {max_rows} rows (including NaN), skipped: {len(globalVars.skipped_sample_indices)}")
    else:
        raise RuntimeError(f"Output CSV file not found: {output_csv_path}")
    
    # ========== Save the results ==========
    headers = [f'obj_{i+1}' for i in range(NUM_OBJECTIVES)] + [f'con_{i+1}' for i in range(NUM_CONSTRAINTS)]
    
    # Save as CSV
    csv_path = os.path.join(globalVars.filepath_samples, f"sample_{globalVars.sampling_counter + 1}.csv")
    df = pd.DataFrame(result, columns=headers)
    df.to_csv(csv_path, index=False)
    print(f"Simpack simulations in sample_{globalVars.sampling_counter + 1} completed.")
    print(f"Total rows: {max_rows}, Valid samples: {max_samples}, Skipped: {len(globalVars.skipped_sample_indices)}")
    globalVars.sampling_counter += 1  # increment the sampling counter




def generate_response_dataset(xx, nSample, nSampleR_obj, NUM_OBJECTIVES, NUM_CONSTRAINTS, constraint_basis_info):
    

    # Initialize the response arrays
    rsvl_obj = np.zeros((nSampleR_obj, NUM_OBJECTIVES))  # objective responses
    # 2D array for the constraint responses (samples, constraints)
    nSampleR_con = constraint_basis_info[0]['nSampleR']
    rsvl_con = np.zeros((nSampleR_con, NUM_CONSTRAINTS))
    
    # Load the data from CSV
    if globalVars.filepath_samples is None:
        raise RuntimeError("globalVars.filepath_samples is not set. Please set the samples folder path first.")
    
    csv_path = os.path.join(globalVars.filepath_samples, f"sample_{globalVars.sampling_counter}.csv")
    
    if os.path.exists(csv_path):
        print(f"Loading response data from: {csv_path}")
        
        # Load the CSV file
        df = pd.read_csv(csv_path)
        
        # Read the data in column order (header ignored)
        data_array = df.values  # convert the whole table to a numpy array
        
        if data_array.shape[1] == (NUM_OBJECTIVES + NUM_CONSTRAINTS):
            # Filter the data according to skipped_sample_indices
            if globalVars.skipped_sample_indices:
                # Convert 1-based to 0-based indices
                skipped_indices_0based = set(idx - 1 for idx in globalVars.skipped_sample_indices)
                
                # Objective data: collect valid indices sequentially
                valid_indices_obj = []
                idx = 0
                while len(valid_indices_obj) < nSampleR_obj:
                    if idx not in skipped_indices_0based:
                        valid_indices_obj.append(idx)
                    idx += 1
                n_extended_obj = idx  # end of the required range
                
                obj_data = data_array[valid_indices_obj, :NUM_OBJECTIVES]
                
                
                # Constraint data: collect valid indices sequentially
                valid_indices_con = []
                idx = 0
                while len(valid_indices_con) < nSampleR_con:
                    if idx not in skipped_indices_0based:
                        valid_indices_con.append(idx)
                    idx += 1
                n_extended_con = idx  # end of the required range
                
                con_data = data_array[valid_indices_con, NUM_OBJECTIVES:NUM_OBJECTIVES+NUM_CONSTRAINTS]
                
                
            else:
                # No skipped samples: use the first rows directly
                if data_array.shape[0] < nSampleR_obj:
                    raise RuntimeError(f"CSV has only {data_array.shape[0]} rows, but need {nSampleR_obj} objective samples")
                
                obj_data = data_array[:nSampleR_obj, :NUM_OBJECTIVES]

                if data_array.shape[0] < nSampleR_con:
                    raise RuntimeError(f"CSV has only {data_array.shape[0]} rows, but need {nSampleR_con} constraint samples")
                
                con_data = data_array[:nSampleR_con, NUM_OBJECTIVES:NUM_OBJECTIVES+NUM_CONSTRAINTS]
                

            ## Objective responses
            rsvl_obj[:, :] = obj_data

            ## Constraint responses as normalized limit-state values (y > 0: safe, y <= 0: failure)
            # Column 0: PEEQ, failure if > 0.05 (eps_lim)       -> 1 - PEEQ/0.05
            # Column 1: x-direction stiffness, failure if < 10 kN/mm (Kx_lim)  -> Kx/10 - 1
            # Column 2: y-direction stiffness, failure if < 100 kN/mm (Ky_lim) -> Ky/100 - 1
            rsvl_con[:, 0] = 1 - con_data[:, 0] / 0.05
            rsvl_con[:, 1] = con_data[:, 1] / 10 - 1
            rsvl_con[:, 2] = con_data[:, 2] / 100 - 1

            ## Print summary
            if globalVars.skipped_sample_indices:
                print(f"  - Skipped {len(skipped_indices_0based)} samples (indices: {globalVars.skipped_sample_indices})")
                print(f"  - Loaded objective data shape: {rsvl_obj.shape} from extended range [0:{n_extended_obj}]")
                print(f"  - Loaded constraint data shape: {rsvl_con.shape} from extended range [0:{n_extended_con}]")
            else:
                print(f"  - Loaded objective data shape: {rsvl_obj.shape}")
                print(f"  - Loaded constraint data shape: {rsvl_con.shape}")

            return rsvl_obj, rsvl_con
        

        else:
            raise RuntimeError(f"CSV has {data_array.shape[1]} columns, but need {NUM_OBJECTIVES + NUM_CONSTRAINTS} columns")
            
    else:
        raise RuntimeError(f"CSV file not found: {csv_path}")

    
